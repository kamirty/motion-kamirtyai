export const IDEA_TEMPLATE_COUNT = TEMPLATES.length;

/**
 * Picks templates that fit the topic (and `hint`, e.g. the full request with its audience), best
 * first; `offset` pages through the rest.
 */
export function suggestIdeas(topic: string, offset = 0, count = 3, hint = ''): IdeaCard[] {
  const hay = normalizeArabic(`${topic} ${hint}`);
  const ranked = TEMPLATES.map((t, i) => ({ t, i, score: t.fits.filter((f) => hay.includes(f)).length }))
    .sort((a, b) => b.score - a.score || a.i - b.i)
    .map((r) => r.t);
  const out: IdeaCard[] = [];
  for (let k = 0; k < Math.min(count, ranked.length); k++) {
    const t = ranked[(offset + k) % ranked.length];
    out.push({ title: t.title(topic), angle: t.angle, outline: t.outline(topic), kinds: t.kinds });
  }
  return out;
}
