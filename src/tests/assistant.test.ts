describe('assistant routing', () => {
  it('has at least six real phrasings for every knowledge entry', () => {
    for (const e of KNOWLEDGE) expect(ROUTES[e.id]?.length ?? 0, e.id).toBeGreaterThanOrEqual(6);
  });

  describe.each(Object.entries(ROUTES))('%s', (id, questions) => {
    it.each(questions)('%s', (q) => {
      expect(ask(q).text).toBe(answerOf(id));
    });
  });

  it.each(OFF_TOPIC)('declines off-topic: %s', (q) => {
    const r = ask(q);
    expect(r.text).toMatch(DECLINE);
    expect(r.ideas).toBeUndefined();
  });

  it.each(GREETINGS)('greets: %s', (q) => expect(ask(q).text).toMatch(/أهلًا/));
  it.each(THANKS)('thanks: %s', (q) => expect(ask(q).text).toMatch(/العفو/));

  it('acknowledges a bare "ok" and offers help on a bare call for help', () => {
    for (const q of ['تمام', 'اوكي', 'طيب']) expect(ask(q).text, q).toMatch(/اسألني متى شئت/);
    for (const q of ['ساعدني', 'مساعدة', 'help', 'ما فهمت']) expect(ask(q).text, q).toMatch(/أستطيع مساعدتك في/);
  });

  it('answers the question inside a greeting or thanks', () => {
    expect(ask('السلام عليكم، كيف أصدر الفيديو؟').text).toBe(answerOf('export'));
    expect(ask('هلا كيف اغير الخط').text).toBe(answerOf('font'));
    expect(ask('شكرا على الأفكار، كيف أصدر؟').text).toBe(answerOf('export'));
  });

  it('asks to rephrase tool questions it cannot place instead of refusing them', () => {
    for (const q of ['كيف احفظ', 'ابي الفيديو يبدأ بسؤال']) expect(ask(q).text, q).toMatch(/لم أفهم سؤالك/);
  });
});

describe('assistant ideas', () => {
  it.each(IDEA_REQUESTS)('%s → %s', (q, topic) => {
    expect(extractIdeaTopic(q)).toBe(topic);
    const r = ask(q);
    expect(r.ideas).toHaveLength(3);
    expect(r.ideas![0].title).toContain(topic);
  });

  it('returns three fitting idea outlines with placeholders, never facts', () => {
    const r = ask('أعطني أفكارًا لدرس عن دورة الماء لطلاب الابتدائي');
    expect(r.ideas).toHaveLength(3);
    expect(r.ideas![0].title).toContain('دورة الماء');
    for (const idea of r.ideas!) expect(idea.title + idea.outline).not.toMatch(/دورة دورة|هرم هرم|قصة قصة|تحدي تحدي/);
    for (const idea of r.ideas!) {
      expect(idea.outline).toContain('[');
      expect(idea.outline).toContain('دورة الماء');
    }
  });

  it('pages through more ideas for the same topic', () => {
    const first = respond('أفكار لفيديو عن النوم', ctx, initialAssistantState);
    const more = respond('أعطني أفكارًا أخرى', ctx, first.state);
    expect(more.reply.ideas!.map((i) => i.title)).not.toEqual(first.reply.ideas!.map((i) => i.title));
    for (const q of ['غيرها', 'فكرة ثانية', 'المزيد']) expect(respond(q, ctx, more.state).reply.ideas, q).toHaveLength(3);
  });

  it('does not treat tool questions after an idea reply as a request for more ideas', () => {
    const first = respond('أفكار لفيديو عن النوم', ctx, initialAssistantState);
    expect(respond('كيف اضيف المزيد من المشاهد', ctx, first.state).reply.text).toBe(answerOf('scenes-manage'));
    expect(respond('الخلفية المتحركة كيف اغيرها', ctx, first.state).reply.text).toBe(answerOf('style'));
  });

  it('asks for a topic when none is given', () => {
    for (const q of ['اقترح علي أفكار', 'ابي افكار', 'اعطني فكرة فيديو', 'ابي فيديو للاطفال', 'ساعدني في الفيديو']) expect(ask(q).text, q).toMatch(/عن أي موضوع/);
  });

  it('keeps a request about the tool itself out of idea mode', () => {
    // "ابي فيديو عمودي" is about the format; "ابي فيديو عن الصور" is a topic.
    expect(ask('ابي فيديو عمودي').text).toBe(answerOf('aspect'));
    expect(ask('ابي احط مقطع فيديو داخل المشهد').text).toBe(answerOf('images'));
    expect(ask('ابي فيديو عن الصور الفوتوغرافية').ideas).toHaveLength(3);
  });
});
